<?php

declare(strict_types=1);

namespace Tests\Unit\Optimize;

use AA\Optimize\MissCacheRouting;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

/** The HTTP probes and the config constants need a live install; the rule, its writing and
 *  the reading of the probe answer do not. */
final class MissCacheRoutingTest extends TestCase
{
    /** the rule e14fe7c8 wrote from the page render - still to be recognised as AA's */
    private const RULE_2026_09_11 = "# Generated by APC-AA - routes a request for a not yet generated file to the\n"
        . "# dispatcher; files already in the cache are served by the web server and never\n"
        . "# reach PHP. Delete this file and AA writes it again (e.g. after moving AA).\n"
        . "<IfModule mod_rewrite.c>\nRewriteEngine On\nRewriteCond %{REQUEST_FILENAME} !-f\n"
        . "RewriteRule ^ /aa-dev/modules/site/site.php [L,QSA]\n</IfModule>\n";

    private string $tmp;

    /** stands for IMG_UPLOAD_PATH, which exists on any install that has uploads */
    protected function setUp(): void
    {
        $this->tmp = sys_get_temp_dir() . '/aa-misscache-routing-' . bin2hex(random_bytes(8));
        mkdir($this->tmp, 0o775);
    }

    protected function tearDown(): void
    {
        @chmod($this->tmp, 0o775);
        array_map('unlink', glob($this->tmp . '/mC/.htaccess*') ?: []);
        @rmdir($this->tmp . '/mC');
        @rmdir($this->tmp);
    }

    public function test_rule_routes_a_miss_to_the_dispatcher_of_the_install(): void
    {
        $rule = (string) MissCacheRouting::rule('/aa-dev/');
        $this->assertStringContainsString("RewriteCond %{REQUEST_FILENAME} !-f\n", $rule, 'a file already in the cache is served by the web server');
        $this->assertStringContainsString("RewriteRule ^ /aa-dev/modules/site/site.php [L,QSA]\n", $rule);
        $this->assertStringContainsString("RewriteRule ^ /modules/site/site.php [L,QSA]\n", (string) MissCacheRouting::rule('/'), 'AA at the domain root');
    }

    /** @return array<string, array{0: string}> */
    public static function unsafeInstallPaths(): array
    {
        return ['space' => ['/a a/'], 'newline' => ["/aaa/\n"], 'relative' => ['aaa/'], 'no trailing slash' => ['/aaa'], 'quote' => ['/a"a/'], 'parent' => ['/../'], 'empty segment' => ['//']];
    }

    /** Apache parses the file: a space or a newline in the target answers 500 for every cached image */
    #[DataProvider('unsafeInstallPaths')]
    public function test_rule_refuses_an_install_path_apache_would_choke_on(string $install_path): void
    {
        $this->assertNull(MissCacheRouting::rule($install_path));
    }

    public function test_missing_rule_is_written_together_with_the_cache_directory(): void
    {
        $dir  = $this->tmp . '/mC';
        $rule = (string) MissCacheRouting::rule('/aaa/');

        $this->assertTrue(MissCacheRouting::writeIfMissing($dir, $rule, 0o775));
        $this->assertStringEqualsFile("$dir/.htaccess", $rule);
        $this->assertSame(["$dir/.htaccess"], glob("$dir/.htaccess*"), 'no temp file left behind');
        $this->assertSame(0o775, fileperms($dir) & 0o7777, 'the mode asked for, whatever the umask - the other PHP user of the uploads writes here too');
        $this->assertSame(0o644, fileperms("$dir/.htaccess") & 0o777);
    }

    /** /aaa/ and /aa-dev/ share the upload directory; the one which wrote the rule keeps it. */
    public function test_existing_rule_is_never_replaced(): void
    {
        $dir = $this->tmp . '/mC';
        MissCacheRouting::writeIfMissing($dir, (string) MissCacheRouting::rule('/aaa/'), 0o775);

        $this->assertTrue(MissCacheRouting::writeIfMissing($dir, (string) MissCacheRouting::rule('/aa-dev/'), 0o775), 'a rule in place is success');
        $this->assertStringEqualsFile("$dir/.htaccess", (string) MissCacheRouting::rule('/aaa/'));
    }

    /** a symlink planted in its place is never written through - it could point at any file of the PHP user */
    public function test_planted_symlink_is_not_written_through(): void
    {
        $dir    = $this->tmp . '/mC';
        $target = $this->tmp . '/target';
        mkdir($dir);
        symlink($target, "$dir/.htaccess");

        $this->assertFalse(MissCacheRouting::writeIfMissing($dir, (string) MissCacheRouting::rule('/aaa/'), 0o775));
        $this->assertFileDoesNotExist($target);
        $this->assertSame([], glob("$dir/.htaccess.*"), 'no temp file left behind');
        unlink("$dir/.htaccess");
    }

    public function test_unwritable_upload_directory_is_reported(): void
    {
        if (function_exists('posix_geteuid') && posix_geteuid() === 0) {
            $this->markTestSkipped('root writes anywhere');
        }
        chmod($this->tmp, 0o555);

        $this->assertFalse(MissCacheRouting::writeIfMissing($this->tmp . '/mC', (string) MissCacheRouting::rule('/aaa/'), 0o775));
    }

    /** @return array<string, array{0: string, 1: bool}> */
    public static function rules(): array
    {
        return [
            'this version, any tree'        => [(string) MissCacheRouting::rule('/aaa/'), true],
            'written by the render 11. 9.'  => [self::RULE_2026_09_11, true],
            'comment edited'                => ["# moved by hand\n" . self::RULE_2026_09_11, true],
            'saved with CRLF and a BOM'     => ["\xEF\xBB\xBF" . str_replace("\n", "\r\n", self::RULE_2026_09_11), true],
            'indented'                      => [str_replace("\nRewrite", "\n    Rewrite", self::RULE_2026_09_11), true],
            'AA at the domain root'         => [(string) MissCacheRouting::rule('/'), true],
            'extra directive'               => [str_replace('</IfModule>', "Header set X-Frame-Options DENY\n</IfModule>", self::RULE_2026_09_11), false],
            'another script'                => [str_replace('site/site.php', 'site/other.php', self::RULE_2026_09_11), false],
            'empty'                         => ['', false],
        ];
    }

    /** a rule which is not AA's survives every write-if-missing, so State Check has to say so */
    #[DataProvider('rules')]
    public function test_aa_rule_is_recognised(string $content, bool $expected): void
    {
        $this->assertSame($expected, MissCacheRouting::isAaRule($content));
    }

    /** @return array<string, array{0: int, 1: string, 2: bool, 3: string}> */
    public static function answers(): array
    {
        return [
            'dispatcher answered its blank'     => [200, 'image/jpeg', true, 'ok'],
            'routed by the server config'       => [200, 'image/jpeg', false, 'ok'],
            'catch-all page instead of image'   => [200, 'text/html; charset=utf-8', true, 'ignored'],
            'not found although the rule is in' => [404, 'text/html', true, 'ignored'],
            'tree disabled on this host'        => [403, 'text/html', true, 'ignored'],
            'not found, no rule'                => [404, 'text/html', false, 'missing'],
            'no answer, rule in place'          => [0, '', true, 'unreachable'],
            'no answer, no rule - write it'     => [0, '', false, 'missing'],
        ];
    }

    /** @return array<string, array{0: int, 1: string, 2: string, 3: bool}> */
    public static function imgPhpAnswers(): array
    {
        $error_image = 'https://example.org/aa/images/blank.gif';
        return [
            'a thumbnail'                          => [200, 'image/jpeg', '', true],
            'cannot read the probe, still answers' => [302, 'text/html', $error_image, true],   // AA tree outside the docroot
            'redirected elsewhere'                 => [301, 'text/html', 'https://example.org/aa/img.php?src=x', false],
            'no answer'                            => [0, '', '', false],
            'a page instead of an image'           => [200, 'text/html', '', false],
        ];
    }

    #[DataProvider('imgPhpAnswers')]
    public function test_img_php_answer(int $status, string $content_type, string $location, bool $expected): void
    {
        $this->assertSame($expected, MissCacheRouting::imgPhpAnswers($status, $content_type, $location, 'https://example.org/aa/images/blank.gif'));
    }

    #[DataProvider('answers')]
    public function test_verdict_on_the_probe_answer(int $status, string $content_type, bool $has_rule, string $expected): void
    {
        $this->assertSame($expected, MissCacheRouting::verdict($status, $content_type, $has_rule));
    }
}
