#!/usr/bin/env bash
# Build the runtime-only tree ("dist") from a source checkout:
#   dev/release/build-dist.sh <source-tree> <output-dir>
# Runs `composer install --no-dev` INSIDE the source tree (its vendor/ is rebuilt), so point it at a CI
# checkout or a scratch copy, never at the live development tree.
set -euo pipefail
src=$(realpath "$1"); dst=$(realpath -m "$2"); here=$(cd "$(dirname "$0")" && pwd)
[ -f "$src/composer.json" ] || { echo "build-dist: not a source tree: $src" >&2; exit 2; }
case "$dst" in "$src"|"$src"/*) echo "build-dist: output must be outside the source tree" >&2; exit 2 ;; esac
# a rsync/CI copy has no VCS to guess the root version from; pin it so installed.php does not churn per build
export COMPOSER_ROOT_VERSION="${COMPOSER_ROOT_VERSION:-dev-main}"
( cd "$src" && composer install --no-dev --optimize-autoloader --no-scripts --no-interaction --no-progress --quiet )
rm -rf "$dst"; mkdir -p "$dst"
rsync -a --delete --filter="merge $here/dist-exclude.txt" "$src/" "$dst/"
{ grep -v -E '^\s*(#|$)' "$here/vendor-prune.txt" || true; } | while IFS= read -r name; do
    find "$dst/vendor" -mindepth 3 -name "$name" -prune -exec rm -rf {} +   # depth 3 = inside vendor/<owner>/<package>/
done
{ grep -v -E '^\s*(#|$)' "$here/vendor-prune-paths.txt" || true; } | while IFS= read -r pat; do
    ( cd "$dst/vendor" && rm -rf -- $pat 2>/dev/null ) || true   # unquoted on purpose: the list holds globs
done
install -m 644 "$here/dist-gitignore" "$dst/.gitignore"
# build stamp read by aa_version() (include/util.php); a source checkout has no release.php
commit=$(git -C "$src" rev-parse HEAD 2>/dev/null || echo unknown)
cdate=$(git -C "$src" log -1 --format=%cI 2>/dev/null || echo unknown)
printf '<?php\n// Generated by dev/release/build-dist.sh - which main commit this runtime tree was built from. Do not edit.\nreturn [%s => %s, %s => %s];\n' \
    "'commit'" "'$commit'" "'date'" "'$cdate'" > "$dst/include/release.php"
# pruning must not remove anything the autoloader points at (a stale classmap entry is a fatal at runtime)
php -r '$c = require $argv[1]; $f = require $argv[2]; $bad = 0;
    foreach (array_merge($c, $f) as $p) { if (!is_file($p)) { fwrite(STDERR, "build-dist: autoload target missing: $p\n"); $bad = 1; } }
    exit($bad);' "$dst/vendor/composer/autoload_classmap.php" "$dst/vendor/composer/autoload_files.php"
echo "build-dist: $(find "$dst" -type f | wc -l) files in $dst"
